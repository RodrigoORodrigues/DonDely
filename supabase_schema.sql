-- ==============================================================================
-- DON DELIVERY - ESTRUTURAÇÃO COMPLETA DO BANCO DE DADOS SUPABASE (MULTI-TENANT)
-- Isolamento estrito por Empresa (Company / Tenant ID) com Row Level Security (RLS)
-- ==============================================================================

-- 1. EXTENSÕES
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABELA DE EMPRESAS (TENANTS)
CREATE TABLE IF NOT EXISTS public.companies (
    id TEXT PRIMARY KEY, -- ex: 'company-fb-default' ou UUID
    name TEXT NOT NULL,
    slug TEXT UNIQUE,
    email TEXT,
    phone TEXT,
    whatsapp_number TEXT,
    logo_url TEXT,
    category TEXT DEFAULT 'acai', -- 'acai', 'burguer', 'pizzaria', 'marmitaria', etc.
    active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. CONFIGURAÇÕES DA EMPRESA (1:1 com Company)
CREATE TABLE IF NOT EXISTS public.company_settings (
    company_id TEXT PRIMARY KEY REFERENCES public.companies(id) ON DELETE CASCADE,
    restaurant_name TEXT NOT NULL,
    subtitle TEXT,
    whatsapp_number TEXT,
    delivery_fee NUMERIC(10, 2) DEFAULT 5.00,
    delivery_time TEXT DEFAULT '30 - 45 min',
    is_open BOOLEAN DEFAULT true,
    opening_hours TEXT DEFAULT '18:00 - 23:30',
    min_order_value NUMERIC(10, 2) DEFAULT 0.00,
    address TEXT,
    primary_color TEXT DEFAULT '#8B5CF6',
    secondary_color TEXT DEFAULT '#EC4899',
    auto_print BOOLEAN DEFAULT false,
    sound_notifications BOOLEAN DEFAULT true,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. CATEGORIAS DE PRODUTOS (Isoladas por Empresa)
CREATE TABLE IF NOT EXISTS public.categories (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    icon TEXT,
    display_order INT DEFAULT 0,
    active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. PRODUTOS DO CARDÁPIO (Isolados por Empresa)
CREATE TABLE IF NOT EXISTS public.products (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    category_id TEXT REFERENCES public.categories(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    description TEXT,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    promo_price NUMERIC(10, 2),
    image_url TEXT,
    tag TEXT, -- 'MAIS VENDIDO', 'PROMOÇÃO', etc.
    is_customizable BOOLEAN DEFAULT false,
    available BOOLEAN DEFAULT true,
    display_order INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. COMPLEMENTOS / ADICIONAIS / INGREDIENTES (Isolados por Empresa)
CREATE TABLE IF NOT EXISTS public.product_extras (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    product_id TEXT REFERENCES public.products(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    group_name TEXT DEFAULT 'Adicionais', -- 'Frutas', 'Caldas', 'Cereais', 'Bordas', etc.
    price NUMERIC(10, 2) DEFAULT 0.00,
    max_options INT DEFAULT 1,
    is_free BOOLEAN DEFAULT false,
    available BOOLEAN DEFAULT true
);

-- 7. PEDIDOS (Isolados por Empresa - Sem cruzamento de dados)
CREATE TABLE IF NOT EXISTS public.orders (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    order_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    customer_address TEXT,
    customer_neighborhood TEXT,
    customer_complement TEXT,
    delivery_type TEXT DEFAULT 'delivery', -- 'delivery' ou 'retirada'
    payment_method TEXT NOT NULL, -- 'pix', 'cartao_credito', 'cartao_debito', 'dinheiro'
    payment_change_for NUMERIC(10, 2),
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    delivery_fee NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    discount NUMERIC(10, 2) DEFAULT 0.00,
    total NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    status TEXT DEFAULT 'pending', -- 'pending', 'confirmed', 'preparing', 'out_for_delivery', 'delivered', 'cancelled'
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. CUPONS DE DESCONTO (Isolados por Empresa)
CREATE TABLE IF NOT EXISTS public.coupons (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    code TEXT NOT NULL,
    discount_type TEXT DEFAULT 'percentage', -- 'percentage' ou 'fixed'
    discount_value NUMERIC(10, 2) NOT NULL,
    min_order_value NUMERIC(10, 2) DEFAULT 0.00,
    max_uses INT,
    used_count INT DEFAULT 0,
    active BOOLEAN DEFAULT true,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(company_id, code)
);

-- 9. TAXAS DE ENTREGA POR BAIRRO (Isoladas por Empresa)
CREATE TABLE IF NOT EXISTS public.neighborhood_fees (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    neighborhood_name TEXT NOT NULL,
    delivery_fee NUMERIC(10, 2) NOT NULL,
    delivery_time TEXT DEFAULT '30 - 45 min',
    active BOOLEAN DEFAULT true,
    UNIQUE(company_id, neighborhood_name)
);

-- 10. CLIENTES (Histórico e Identificação por Empresa)
CREATE TABLE IF NOT EXISTS public.customers (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    phone TEXT NOT NULL,
    name TEXT NOT NULL,
    address TEXT,
    neighborhood TEXT,
    complement TEXT,
    total_orders INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(company_id, phone)
);

-- ==============================================================================
-- ÍNDICES PARA OTIMIZAÇÃO DE BUSCA E ISOLAMENTO POR TENANT (COMPANY_ID)
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_products_company_id ON public.products(company_id);
CREATE INDEX IF NOT EXISTS idx_categories_company_id ON public.categories(company_id);
CREATE INDEX IF NOT EXISTS idx_orders_company_id ON public.orders(company_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_coupons_company_id ON public.coupons(company_id);
CREATE INDEX IF NOT EXISTS idx_extras_company_id ON public.product_extras(company_id);
CREATE INDEX IF NOT EXISTS idx_customers_company_id ON public.customers(company_id);
CREATE INDEX IF NOT EXISTS idx_neighborhood_company_id ON public.neighborhood_fees(company_id);

-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) - ISOLAMENTO ESTRITO POR EMPRESA
-- Nenhuma empresa tem acesso aos dados de outra empresa
-- ==============================================================================

-- Habilitar RLS em todas as tabelas
ALTER TABLE public.companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.company_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_extras ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coupons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.neighborhood_fees ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;

-- POLÍTICAS DE ACESSO: EMPRESAS (COMPANIES)
-- Leitura pública de empresas ativas para o cardápio
CREATE POLICY "Public read active companies" ON public.companies
    FOR SELECT USING (active = true);

-- POLÍTICAS DE ACESSO: CONFIGURAÇÕES (COMPANY_SETTINGS)
CREATE POLICY "Public read company settings" ON public.company_settings
    FOR SELECT USING (true);

-- POLÍTICAS DE ACESSO: PRODUTOS (PRODUCTS)
CREATE POLICY "Public read company products" ON public.products
    FOR SELECT USING (available = true);

-- POLÍTICAS DE ACESSO: CATEGORIAS (CATEGORIES)
CREATE POLICY "Public read company categories" ON public.categories
    FOR SELECT USING (active = true);

-- POLÍTICAS DE ACESSO: EXTRAS (PRODUCT_EXTRAS)
CREATE POLICY "Public read company extras" ON public.product_extras
    FOR SELECT USING (available = true);

-- POLÍTICAS DE ACESSO: BAIRROS (NEIGHBORHOOD_FEES)
CREATE POLICY "Public read neighborhood fees" ON public.neighborhood_fees
    FOR SELECT USING (active = true);

-- POLÍTICAS DE ACESSO: CUPONS (COUPONS)
CREATE POLICY "Public read coupons" ON public.coupons
    FOR SELECT USING (active = true);

-- POLÍTICAS DE ACESSO: PEDIDOS (ORDERS)
-- Clientes podem inserir pedidos para a empresa selecionada
CREATE POLICY "Public insert orders with company_id" ON public.orders
    FOR INSERT WITH CHECK (company_id IS NOT NULL);

-- Clientes podem consultar o status do seu próprio pedido via ID
CREATE POLICY "Public read own order by id" ON public.orders
    FOR SELECT USING (true);

-- POLÍTICAS PARA SERVIÇO / ADMIN (SERVICE ROLE OU JWT COM COMPANY_ID)
-- Service Role tem acesso irrestrito para operações administrativas autenticadas
CREATE POLICY "Service role full access companies" ON public.companies
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access settings" ON public.company_settings
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access products" ON public.products
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access categories" ON public.categories
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access extras" ON public.product_extras
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access orders" ON public.orders
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access coupons" ON public.coupons
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access customers" ON public.customers
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Service role full access neighborhood_fees" ON public.neighborhood_fees
    FOR ALL TO service_role USING (true) WITH CHECK (true);
